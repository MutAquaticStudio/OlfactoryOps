import assert from 'node:assert/strict'
import { readFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'

const root = new URL('..', import.meta.url)
const source = (path) => readFileSync(new URL(path, root), 'utf8').replaceAll('\r\n', '\n')

export function verifyRc13PublicAuthContract() {
  const app = source('src/App.tsx')
  const platform = source('src/features/v2-platform/V2PlatformApp.tsx')
  const worker = source('worker/v2-api/service-container.ts')
  const controller = source('server/src/routes/v2-platform.controller.ts')
  const service = source('services/platform/src/service.ts')
  const migration = source('infra/postgres/migrations/0026_platform_password_resets.sql')
  const resetDispatch = source('worker/v2-api/cloud-password-reset-dispatch.ts')
  const delivery = source('worker/cloud-runtime/password-reset-delivery.ts')
  const cloudRuntime = source('worker/cloud-runtime/index.ts')
  const cloudRuntimeConfig = source('wrangler.v2-cloud-runtime-production.example.toml')
  const serviceWorker = source('public/sw.js')
  const clientEntry = source('src/main.tsx')

  for (const route of ["'/login'", "'/signup'", "'/forgot-password'", "'/reset-password'", "'/verify-email'"]) assert.ok(app.includes(route), `V2 owns ${route}`)
  assert.ok(app.includes('LegacyUnauthenticatedRedirect'), 'legacy unauthenticated users redirect to V2')
  assert.ok(!app.includes('function AuthGateway'), 'legacy public auth shell removed from the application bundle')
  assert.ok(!app.includes("requestApi<LoginResponse>('/auth/login'"), 'legacy login request removed')
  assert.ok(!app.includes("requestApi<SignupResponse>('/auth/signup'"), 'legacy signup request removed')
  assert.ok(!app.includes("requestApi<{ accepted: boolean }>('/auth/password-reset/request'"), 'legacy reset request call removed')
  assert.ok(!app.includes("requestApi<{ accepted: boolean }>('/auth/password-reset/confirm'"), 'legacy reset confirm call removed')
  assert.ok(platform.includes("'/auth/password-reset/request'"), 'V2 reset request path')
  assert.ok(platform.includes("'/auth/password-reset/confirm'"), 'V2 reset confirm path')
  assert.ok(platform.includes('v2-legacy-auth-recovery'), 'legacy links reach neutral V2 recovery')
  assert.ok(controller.includes("@Post('auth/password-reset/request')"), 'V2 reset request endpoint')
  assert.ok(controller.includes("@Post('auth/password-reset/confirm')"), 'V2 reset confirm endpoint')
  assert.ok(worker.includes('V2_PASSWORD_RESET_ENCRYPTION_KEY'), 'dedicated reset secret binding required')
  assert.ok(service.includes('payloadCiphertext: sealSecret'), 'outbox reset payload encrypted')
  assert.ok(service.includes("resetPath: '/v2/reset-password'"), 'new reset mail uses the V2-only confirmation path')
  assert.ok(service.includes('passwordResetDispatcher'), 'committed reset outbox is dispatched through an internal adapter')
  assert.ok(service.includes('revokeAllUserSessions'), 'reset revokes V2 sessions')
  assert.ok(migration.includes('v2_password_resets'), 'additive reset table')
  assert.ok(migration.includes('FORCE ROW LEVEL SECURITY'), 'reset table forces RLS')
  assert.ok(migration.includes("current_setting('app.password_reset_hash', true)"), 'reset lookup uses a scoped opaque token verifier')
  assert.ok(migration.includes('revoke every V2 session'), 'reset session revocation is explicitly scoped in RLS policy')
  assert.ok(resetDispatch.includes('internal/notification-dispatch'), 'reset dispatch stays on the private Cloud Runtime binding')
  assert.ok(!resetDispatch.includes('http://') && !resetDispatch.includes('https://api.'), 'reset dispatch has no browser-addressable fallback')
  assert.ok(delivery.includes("eventTypes: ['PASSWORD_RESET']"), 'recovery consumer claims only reset outbox events')
  assert.ok(delivery.includes('respectPreferences: false'), 'reset delivery cannot be suppressed by product notifications preferences')
  assert.ok(delivery.includes('openSecret') && delivery.includes('sendResendEmail'), 'reset mail decrypts only in the delivery runtime')
  assert.ok(!delivery.includes('console.'), 'delivery runtime never logs reset payloads')
  assert.ok(cloudRuntime.includes("'/internal/notification-dispatch'"), 'Cloud Runtime accepts a dedicated typed notification dispatch')
  for (const secret of ['V2_PASSWORD_RESET_ENCRYPTION_KEY', 'RESEND_API_KEY', 'EMAIL_FROM']) assert.ok(cloudRuntimeConfig.includes(secret), `runtime config declares ${secret} by name only`)
  assert.ok(cloudRuntimeConfig.includes('PASSWORD_RESET_DELIVERY_ENABLED = "true"'), 'production reset mail delivery is explicit')
  assert.ok(serviceWorker.includes('CACHE_PREFIX'), 'release-scoped static cache')
  assert.ok(serviceWorker.includes("fetch(request, { cache: 'no-store' })"), 'navigation is network-first without shell fallback')
  assert.ok(!serviceWorker.includes("caches.match('/')"), 'stale shell fallback removed')
  assert.ok(clientEntry.includes('VITE_RELEASE_SHA'), 'service worker registration is release-SHA scoped')
  assert.ok(clientEntry.includes('controllerchange'), 'service worker can perform one controlled upgrade reload')
  assert.ok(clientEntry.includes('updateViaCache'), 'service worker update bypasses stale registration metadata')
  console.log('RC13_PUBLIC_AUTH_CONTRACT=PASS')
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) verifyRc13PublicAuthContract()
